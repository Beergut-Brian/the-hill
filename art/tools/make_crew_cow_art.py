# ------------------------------------------------------------------------------ 1. reduce (optional)
def retrace():
    sys.path.insert(0, os.path.join(LIB, "tools", "pixel"))
    import trace3d as T3
    T3.SRC = SRC
    out = ['"""Generated by art/tools/make_crew_cow_art.py --retrace from the 3D trace renders. Fill only (no',
           'outline), facing screen-left as rendered; "." is transparent. Do not edit: re-run the tool."""', "",
           "BASES = {"]
    for cid, jobs in JOBS.items():
        T3.PAL[cid] = PAL[cid]
        T3.CANVAS[cid] = FRAME[cid]
        name, view, tgt = SCALE_FROM[cid]
        m = json.load(open(os.path.join(SRC, name + ".json")))
        s = (tgt - 2) / (m["views"][view]["height_m"] * m["px_per_m"])
        out.append(f" {cid!r}: {{")
        for key, tname, tview in jobs:
            # trace3d.reduce reads <cid>[_<tag>].json
            tag = tname[len(cid) + 1:] if tname.startswith(cid + "_") else ""
            _k, rows = T3.reduce(cid, tag, tview, s)
            out.append(f"  {key!r}: [")
            out += [f"   {r!r}," for r in rows]
            out.append("  ],")
            print("traced", cid, key, f"{len(rows[0])}x{len(rows)}")
        out.append(" },")
    out.append("}")
    open(DATA, "w").write("\n".join(out) + "\n")
    print("wrote", os.path.relpath(DATA, ROOT))


# ------------------------------------------------------------------------------ 2. hand-clean
def grid(rows):
    return [list(r) for r in rows]


def put(g, x, y, ch, only_filled=False):
    if 0 <= y < len(g) and 0 <= x < len(g[0]) and (not only_filled or g[y][x] != "."):
        g[y][x] = ch


def cells(g, ch):
    return [(x, y) for y, r in enumerate(g) for x, c in enumerate(r) if c == ch]


def bbox(pts):
    xs = [p[0] for p in pts]; ys = [p[1] for p in pts]
    return min(xs), min(ys), max(xs), max(ys)


def clean_gnome(key, g):
    """At 32 px the trace keeps the cone, beard, vest and boots; it drops the face and smears the hard
    hat and whistle. Put back (renders face left): the hard-hat dome on the cone tip, the eye, the brow,
    a round nose, and the whistle as a whistle: a 2 x 2 yellow barrel with a dark slot and a 1 px
    mouthpiece, hanging on the chest below the beard tip (rest poses), or held out in front of the face,
    clear of the beard, with sound lines (whistle)."""
    hat = cells(g, "c")
    if not hat:
        return g
    hx0, hy0, hx1, _ = bbox(hat)
    tip = [x for x, y in hat if y == hy0]
    tx = (min(tip) + max(tip)) // 2
    face_top = min(y for _x, y in cells(g, "s")) if cells(g, "s") else len(g)
    for y in range(min(face_top, len(g))):        # the hard hat: a white dome sitting on the tip (the
        for x in range(len(g[0])):                # vest stripes share its cream: leave those alone)
            if g[y][x] in "hb":
                g[y][x] = "c" if y > hy0 + 1 else "h"
    for dx in (-1, 0, 1):
        put(g, tx + dx, hy0 - 1, "h"); put(g, tx + dx, hy0, "h")
    put(g, tx - 2, hy0, "h"); put(g, tx + 2, hy0, "h"); put(g, tx, hy0 - 2, "h")
    # face band: the skin rows between the hat brim and the beard
    skin = cells(g, "s")
    beard = cells(g, "b")
    if not skin or not beard:
        return g
    bx0, by0, bx1, by1 = bbox(beard)
    face = [(x, y) for x, y in skin if y < by0 + 3]
    if face:
        fx0, fy0, fx1, fy1 = bbox(face)
        side = key != "idle" and key != "cheer"
        if side:                                    # faces left: nose at the front, eye behind it
            nx = fx0
            for y in (fy1 - 1, fy1):
                put(g, nx, y, "n"); put(g, nx + 1, y, "n")
            put(g, nx - 1, fy1, "n")
            put(g, nx + 3, fy0, "o")
            put(g, nx + 2, fy0 - 1, "b", True); put(g, nx + 3, fy0 - 1, "b", True); put(g, nx + 4, fy0 - 1, "b", True)
        else:
            cx = (fx0 + fx1) // 2
            for dx in (-1, 0, 1):
                put(g, cx + dx, fy1, "n")
            put(g, cx, fy1 - 1, "n")
            put(g, cx - 3, fy0, "o"); put(g, cx + 3, fy0, "o")
            if key == "cheer":
                put(g, cx - 3, fy0, "s"); put(g, cx + 3, fy0, "s")
                for ex in (cx - 3, cx + 3):         # happy closed arcs
                    put(g, ex - 1, fy0 + 1 if fy0 + 1 <= fy1 else fy0, "o"); put(g, ex + 1, fy0 + 1 if fy0 + 1 <= fy1 else fy0, "o")
                    put(g, ex, fy0, "o")
            for ex in (cx - 3, cx + 3):
                for dx in (-1, 0, 1):
                    put(g, ex + dx, fy0 - 1, "b", True)
    # the whistle: clear the smeared yellow, then draw it where the master holds it
    for x, y in cells(g, "y"):
        g[y][x] = "v" if y > by1 - 2 else ("b" if (x, y) in beard else "s")
    if key == "whistle":
        # held at the corner of the mouth, poking out IN FRONT of the face (left), never inside the beard
        wy = fy1 + 1 if face else by0 + 1
        front = min(x for y in range(wy - 1, wy + 3) for x in range(len(g[0])) if g[y][x] != ".")
        wx = front - 3                              # the barrel fully outside the face and beard
        for x, y in ((wx, wy), (wx + 1, wy), (wx, wy + 1), (wx + 1, wy + 1)):
            put(g, x, y, "y")
        put(g, wx + 2, wy, "y"); put(g, wx + 3, wy, "y", True)   # mouthpiece into the corner of the mouth
        put(g, wx + 1, wy, "k")                     # the slot on top
        for x, y in cells(g, "v"):                 # the hand lifting it: a skin knuckle under the barrel
            pass
        put(g, wx + 1, wy + 2, "s"); put(g, wx + 2, wy + 2, "s"); put(g, wx + 2, wy + 3, "v")   # fist + sleeve
        # sound lines, out in front with a gap from the barrel; "Y" = drawn after the outline (no
        # dark rim), so they read as lines and do not clump onto the whistle
        for i in range(3):
            put(g, wx - 4, wy - 1 + i, "Y")
        put(g, wx - 3, wy - 3, "Y"); put(g, wx - 4, wy - 4, "Y")
        put(g, wx - 3, wy + 3, "Y"); put(g, wx - 4, wy + 4, "Y")
    else:
        # hangs on the chest just below the beard tip, on the wood cord
        tipx = [x for x, y in beard if y == by1]
        cxw = (min(tipx) + max(tipx)) // 2
        wy = by1 + 1
        if key in ("idle", "cheer"):
            # front: a 3-wide barrel, dark slot on top, the cord's two strands up to the beard
            put(g, cxw - 1, wy, "y"); put(g, cxw, wy, "k"); put(g, cxw + 1, wy, "y")
            put(g, cxw - 1, wy + 1, "y"); put(g, cxw, wy + 1, "y"); put(g, cxw + 1, wy + 1, "y")
            put(g, cxw - 2, wy, "w"); put(g, cxw + 2, wy, "w")
        else:
            put(g, cxw - 1, wy, "y"); put(g, cxw, wy, "y"); put(g, cxw - 1, wy + 1, "y"); put(g, cxw, wy + 1, "y")
            put(g, cxw - 2, wy, "y")
            put(g, cxw, wy, "k")
    return g


def clean_cow(key, g):
    """The library cow's hand-clean (eye and nostril pixels the vote drops), plus the pail: a teal
    bucket with a grey rim and a handle up to the bite point, so it reads as a pail, not a box."""
    mz = cells(g, "p")
    if mz:
        ys = {y for _x, y in mz}
        bot = max(ys); top = bot
        while top - 1 in ys:
            top -= 1
        mz = [(x, y) for x, y in mz if top <= y <= bot]
        if key != "graze":
            t = min(y for _x, y in mz)
            xs = [x for x, y in mz if y == t]
            put(g, max(xs) + 2, t - 2, "o", True)
            nx = [x for x, y in mz if y == t + 1]
            if nx:
                put(g, min(nx) + 1, t + 1, "n", True)
    for y, r in enumerate(g):                       # eye on the black face patch gets a coat rim
        for x, c in enumerate(r):
            if c == "o":
                for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1), (1, -1), (-1, -1)):
                    if 0 <= y + dy < len(g) and 0 <= x + dx < len(r) and g[y + dy][x + dx] == "k":
                        g[y + dy][x + dx] = "w"
    pail = cells(g, "t") + cells(g, "r")
    if pail:
        px0, py0, px1, py1 = bbox(pail)
        for x, y in pail:
            g[y][x] = "."
        w = max(5, px1 - px0 + 1)
        h = max(5, py1 - py0 + 1)
        x0 = px1 - w + 1
        y0 = py1 - h + 1 + 2                         # hang it 2 px lower so the handle shows under the muzzle
        py1 += 2
        for y in range(y0, py1 + 1):                # a bucket, a touch narrower at the bottom
            inset = 1 if y == py1 else 0
            for x in range(x0 + inset, x0 + w - inset):
                put(g, x, y, "t")
        for x in range(x0, x0 + w):                  # the rim
            put(g, x, y0, "r")
        put(g, x0 + 1, y0 + 2, "r")                   # a shine
        # the handle: an arc from the rim corners up to the mouth (the bite point is at the muzzle)
        hx = x0 + w // 2                              # the handle: a grey bail from the rim up into her mouth
        put(g, x0, y0 - 1, "r"); put(g, x0 + w - 1, y0 - 1, "r")
        for x in range(x0 + 1, x0 + w - 1):
            if g[y0 - 2][x] == ".":
                put(g, x, y0 - 2, "r")
    return g


# ------------------------------------------------------------------------------ 3. sprites + sheets
def sprite(rows, pal):
    h, w = len(rows), len(rows[0])
    im = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch != ".":
                im.putpixel((x, y), rgba(pal[ch]))
    return im


def outline(im, col=OUT):
    """1 px outline, 4-connected (the library's px.outline)."""
    from px import outline as po
    return po(im, col)


def fit(im, fw, fh):
    """Feet on the bottom row, centred on the frame; mirrored to face right."""
    im = im.transpose(Image.FLIP_LEFT_RIGHT)
    bb = im.getbbox()
    fig = im.crop(bb)
    assert fig.width <= fw and fig.height <= fh, (fig.size, fw, fh)
    out = Image.new("RGBA", (fw, fh), (0, 0, 0, 0))
    out.alpha_composite(fig, ((fw - fig.width) // 2, fh - fig.height))
    return out


def anchor_x(im_full, fw):
    """Horizontal shift so the body (not a pail or tail) centres on the pivot: unused, kept simple."""
    return 0


def build():
    sys.path.insert(0, HERE)
    sys.path.insert(0, os.path.join(HERE, "characters"))
    import importlib
    import crew_cow_traced as D
    importlib.reload(D)
    frames = {}
    for cid, bases in D.BASES.items():
        clean = clean_gnome if cid == "gnome_crew" else clean_cow
        fw, fh = FRAME[cid]
        for key, rows in bases.items():
            g = clean(key, grid(rows))
            body = ["".join(c if c != "Y" else "." for c in r) for r in g]
            im = outline(sprite(body, PAL[cid]))
            lines = ["".join(c if c == "Y" else "." for c in r) for r in g]
            im.alpha_composite(sprite(lines, {"Y": PAL[cid].get("y", "#FFD23F")}))
            frames[(cid, key)] = im
        # one shared horizontal anchor per sheet: the body's centre in the idle frame
    return frames


def place(frames, cid, keys, fw, fh):
    """Keeps every frame on the same ground line and the same body x: crop by the union bbox."""
    ims = [frames[(cid, k)].transpose(Image.FLIP_LEFT_RIGHT) for k in keys]
    keycols = [rgba(PAL[cid][c])[:3] for c in ("c",)] if cid == "gnome_crew" else \
        [rgba(PAL[cid][c])[:3] for c in ("w", "k")]
    out = []
    for im in ims:
        bb = im.getbbox()
        # bottom on the frame's last row; x so the anchor mass (cone / body) sits on the frame centre,
        # nudged right for the cow so a pail in front still fits
        xs = [x for y in range(im.height) for x in range(im.width) if im.getpixel((x, y))[3] and im.getpixel((x, y))[:3] in keycols]
        cx = sum(xs) / len(xs)
        dx = round(fw / 2 - cx) - (3 if cid == "cow" else 0)
        dy = fh - bb[3]
        f = Image.new("RGBA", (fw, fh), (0, 0, 0, 0))
        f.alpha_composite(im, (dx, dy)) if dx >= 0 and dy >= 0 else f.paste(im, (dx, dy), im)
        out.append(f)
    return out


CREW_ROWS = [("idle", ["idle", "idle_b"], 2), ("march", ["march1", "march_mid", "march2", "march_mid"], 6),
             ("cheer", ["cheer", "idle"], 4), ("whistle", ["whistle"], 0), ("idle_side", ["idle_side"], 0)]
COW_ROWS = [("idle", ["idle"], 0), ("walk", ["trot1", "idle", "trot2", "idle"], 6), ("trot", ["trot1", "trot2"], 8),
            ("graze", ["graze"], 0), ("hop", ["hop"], 0),
            ("pail", ["pail"], 0), ("pail_walk", ["pail_trot1", "pail", "pail_trot2", "pail"], 6)]


def bob(im, cut):
    """Idle frame 2: everything above row `cut` sinks 1 px (a breath)."""
    from px import OUT as O
    base = im.copy()
    px = base.load()
    o = rgba(O)
    out = Image.new("RGBA", im.size, (0, 0, 0, 0))
    out.alpha_composite(im.crop((0, cut, im.width, im.height)), (0, cut))
    out.alpha_composite(im.crop((0, 0, im.width, cut)), (0, 1))
    return out


def sheets(frames):
    made = {}
    for cid, rows, file in (("gnome_crew", CREW_ROWS, "characters/gnome_crew.png"), ("cow", COW_ROWS, "characters/cow.png")):
        fw, fh = FRAME[cid]
        cache = {}
        allkeys = sorted({k for _n, ks, _f in rows for k in ks if k != "idle_b"})
        for k, im in zip(allkeys, place(frames, cid, allkeys, fw, fh)):
            cache[k] = im
        if cid == "gnome_crew":
            cache["idle_b"] = bob(cache["idle"], fh - 9)
        ncol = max(len(ks) for _n, ks, _f in rows)
        sheet = Image.new("RGBA", (ncol * fw, len(rows) * fh), (0, 0, 0, 0))
        man_rows = {}
        for ri, (name, ks, fps) in enumerate(rows):
            for ci, k in enumerate(ks):
                sheet.alpha_composite(cache[k], (ci * fw, ri * fh))
            man_rows[name] = {"row": ri, "frames": len(ks), "fps": fps}
        sheet.save(os.path.join(SPRITES, file))
        made[cid] = (file, fw, fh, man_rows, cache)
    return made


def manifest(made):
    path = os.path.join(SPRITES, "manifest.json")
    m = json.load(open(path))
    f, fw, fh, rows, _c = made["gnome_crew"]
    m["gnome_crew"] = {"file": f, "frame": [fw, fh], "pivot": [fw // 2, fh], "rows": rows, "facing": "right",
                       "note": "Gnome crew: traced from the Gnome Foreman's 3D master (no clipboard); whistle on the chest "
                               "below the beard, held out in front of the face in `whistle`. art/tools/make_crew_cow_art.py"}
    f, fw, fh, rows, _c = made["cow"]
    m["cow"] = {"file": f, "frame": [fw, fh], "pivot": [fw // 2, fh], "rows": rows, "facing": "right",
                "note": "Barn cow: traced from the cow proposal's 3D master (quadruped), pail in the mouth (in_mouth). "
                        "art/tools/make_crew_cow_art.py"}
    with open(path, "w") as fo:
        json.dump(m, fo, indent=1, sort_keys=True)
        fo.write("\n")


def main():
    if "--retrace" in sys.argv:
        retrace()
    made = sheets(build())
    manifest(made)
    print("wrote", {k: v[0] for k, v in made.items()})
    if "--check" in sys.argv:
        import crew_cow_check
        crew_cow_check.main(made, sys.argv[sys.argv.index("--check") + 1])


if __name__ == "__main__":
    main()
