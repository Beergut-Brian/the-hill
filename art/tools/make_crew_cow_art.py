"""The Gnome crew sheet and the cow sheet (V-09), traced from their 3D masters in openjar-characters.

    python3 art/tools/make_crew_cow_art.py            # sheets + manifest entries (no Blender, no library needed)
    python3 art/tools/make_crew_cow_art.py --retrace  # re-reduce .scratch/trace/*.png into crew_cow_traced.py first
    python3 art/tools/make_crew_cow_art.py --check DIR  # also write the read-check pictures to DIR

Masters (read-only, ~/openjar/openjar-characters):
  - Gnome crew: characters/gnome_foreman/jarling.json (approved D49 a, the whistle fix) minus the clipboard
    (the Foreman keeps the clipboard; his crew are workers). Scratch params: .scratch/gnome_crew.json.
  - Cow: proposals/cow/jarling.json (Patience, body type `quadruped`, a proposal), the pail on the `mouth`
    slot with hold style `in_mouth` (avatar/gear/pail.json grip_r on the bite point, hold.attach_mouth).
Trace renders (flat colour, 512 px per 1.2 m) come from avatar/kit/render_trace.py; the pail ones from a
scratch copy that calls hold.attach_mouth for mouth items (render_trace's --gear only knows hand items).
Reduction: the library's trace3d.reduce (palette snap + majority vote per sprite pixel), then the
hand-clean below, then the library's 1 px #2A1E2C outline. Renders face screen-left; the sheets are
mirrored to face right ("facing": "right" in the manifest).
"""
